export async function loadRivers(): Promise<Reach[]> {
  const res = await fetch(`${import.meta.env.BASE_URL}data/rivers.json`);
  return markBorderRivers((await res.json()).reaches);
}

// Border rivers (Mekong, Moei, Kolok…) zig-zag across the line, so their reaches alternate between
// "midpoint in Thailand" and not. Treat a reach as Thai when its upstream or downstream neighbour
// is — one step of dilation makes border rivers continuous without swallowing neighbours' rivers.
export function markBorderRivers(reaches: Reach[]): Reach[] {
  const byId = new Map(reaches.map((r) => [r.id, r]));
  const thaiUpstreamOf = new Set<number>();
  for (const r of reaches) if (r.th) thaiUpstreamOf.add(r.down);
  const add = reaches.filter((r) => !r.th && (byId.get(r.down)?.th || thaiUpstreamOf.has(r.id)));
  for (const r of add) r.th = 1;
  return reaches;
}

export async function loadDischarge(): Promise<Discharge> {
  const res = await fetch(`${import.meta.env.BASE_URL}data/discharge.json`);
  const d: Discharge = await res.json();
  // GloFAS occasionally has gaps — carry the last value forward.
  for (const g of d.gauges) {
    let last = g.series.find((v) => v != null) ?? 0;
    g.series = g.series.map((v) => (v == null ? last : (last = v)));
  }
  return d;
}

// ---------- live GloFAS refresh ----------
// The baked history is regenerated by `npm run data`. At runtime we top it up with the latest
// analysis day and the fresh 30-day forecast so "today" really is today.

const LIVE_KEY = 'waterways.glofas.v1';

export async function refreshDischarge(d: Discharge): Promise<boolean> {
  const today = new Date().toISOString().slice(0, 10);
  if (d.forecastFrom >= today) return false;

  let cached: { day: string; time: string[]; series: number[][] } | null = null;
  try {
    const raw = localStorage.getItem(LIVE_KEY);
    if (raw) cached = JSON.parse(raw);
  } catch {
    /* storage unavailable */
  }

  // Ask for enough past days to close the gap since the baked file (Open-Meteo allows up to 92).
  const behind = Math.round((Date.parse(today) - Date.parse(d.forecastFrom)) / 86400e3);
  const pastDays = Math.min(92, Math.max(7, behind + 2));

  if (!cached || cached.day !== today) {
    const time: string[] = [];
    const series: number[][] = [];
    for (let i = 0; i < d.gauges.length; i += 60) {
      const batch = d.gauges.slice(i, i + 60);
      const params = new URLSearchParams({
        latitude: batch.map((g) => g.cell[1]).join(','),
        longitude: batch.map((g) => g.cell[0]).join(','),
        daily: 'river_discharge',
        past_days: String(pastDays),
        forecast_days: '30',
      });
      const res = await fetch(`https://flood-api.open-meteo.com/v1/flood?${params}`);
      if (!res.ok) return false;
      const json = await res.json();
      for (const loc of Array.isArray(json) ? json : [json]) {
        if (!time.length) time.push(...loc.daily.time);
        series.push(loc.daily.river_discharge.map((v: number | null) => v ?? 0));
      }
    }
    cached = { day: today, time, series };
    try {
      localStorage.setItem(LIVE_KEY, JSON.stringify(cached));
    } catch {
      /* ignore */
    }
  }

  // Splice: keep history up to the first live day, then append the live window.
  const cut = d.time.indexOf(cached.time[0]);
  const keep = cut === -1 ? d.time.length : cut;
  d.time = [...d.time.slice(0, keep), ...cached.time];
  d.gauges.forEach((g, k) => {
    g.series = [...g.series.slice(0, keep), ...cached!.series[k]];
  });
  d.forecastFrom = today;
  return true;
}

// ---------- ThaiWater (HII) ----------

const TW = 'https://api-v3.thaiwater.net/api/v1/thaiwater30/public';
const num = (v: unknown) => (v == null || v === '' || !Number.isFinite(Number(v)) ? null : Number(v));

export async function loadWaterLevels(): Promise<WaterStation[]> {
  const res = await fetch(`${TW}/waterlevel_load`);
  if (!res.ok) throw new Error(`ThaiWater HTTP ${res.status}`);
  const json = await res.json();
  const rows: any[] = json.waterlevel_data?.data ?? [];
  return rows
    .filter((r) => r.station?.tele_station_lat && r.situation_level)
    .map((r) => ({
      id: r.station.id,
      name: r.station.tele_station_name?.th || r.station.tele_station_name?.en || '',
      nameEn: r.station.tele_station_name?.en || r.station.tele_station_name?.th || '',
      province: r.geocode?.province_name?.th ?? '',
      provinceEn: r.geocode?.province_name?.en ?? r.geocode?.province_name?.th ?? '',
      basin: r.basin?.basin_name?.th ?? '',
      basinEn: (r.basin?.basin_name?.en ?? '').replace(/ Basin Basin$/, ' Basin'),
      canal: /คลอง/.test(r.station.tele_station_name?.th ?? '') || /khlong|canal/i.test(r.station.tele_station_name?.en ?? ''),
      lon: r.station.tele_station_long,
      lat: r.station.tele_station_lat,
      msl: num(r.waterlevel_msl),
      prev: num(r.waterlevel_msl_previous),
      bankPct: num(r.storage_percent),
      bankDiff: num(r.diff_wl_bank),
      overBank: String(r.diff_wl_bank_text ?? '').includes('ล้น'),
      level: Number(r.situation_level),
      time: r.waterlevel_datetime,
    }));
}

export async function loadRain(): Promise<RainStation[]> {
  const res = await fetch(`${TW}/rain_24h`);
  if (!res.ok) throw new Error(`ThaiWater HTTP ${res.status}`);
  const json = await res.json();
  const rows: any[] = json.data ?? [];
  return rows
    .filter((r) => r.station?.tele_station_lat && r.rain_24h != null)
    .map((r) => ({
      id: r.station.id,
      name: r.station.tele_station_name?.th || r.station.tele_station_name?.en || '',
      nameEn: r.station.tele_station_name?.en || r.station.tele_station_name?.th || '',
      province: r.geocode?.province_name?.th ?? '',
      provinceEn: r.geocode?.province_name?.en ?? r.geocode?.province_name?.th ?? '',
      lon: r.station.tele_station_long,
      lat: r.station.tele_station_lat,
      mm24: Number(r.rain_24h),
      mm1: num(r.rain_1h),
      time: r.rainfall_datetime,
    }));
}

// ---------- RainViewer radar ----------

export async function loadRadar(): Promise<RadarFrame[]> {
  const res = await fetch('https://api.rainviewer.com/public/weather-maps.json');
  const json = await res.json();
  const frames: { time: number; path: string }[] = json.radar?.past ?? [];
  // Colour scheme 2 ("universal blue"), smoothed, snow shown.
  return frames.map((f) => ({ time: f.time, url: `${json.host}${f.path}/256/{z}/{x}/{y}/2/1_1.png` }));
}

