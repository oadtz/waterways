// Data loading: baked river network + discharge history, and live public feeds.

export type Reach = {
  id: number;
  down: number;
  main: number;
  q: number; // HydroRIVERS long-term mean discharge, m³/s
  ord: number;
  up: number;
  len: number;
  c: [number, number][];
  th: 0 | 1; // midpoint inside Thailand
};

export type Gauge = {
  reach: number;
  p: [number, number];
  cell: [number, number];
  q: number;
  series: (number | null)[];
};

export type Discharge = {
  source: string;
  generated: string;
  time: string[];
  forecastFrom: string;
  gauges: Gauge[];
  assign: number[];
};

